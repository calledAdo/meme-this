"""Copy MemeArena and LpLocker ABIs into the web app. Run `forge build` first."""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
parts = []
for name, path in [("memeArenaAbi", "out/MemeArena.sol/MemeArena.json"), ("lpLockerAbi", "out/LpLocker.sol/LpLocker.json")]:
    abi = json.loads((root / path).read_text())["abi"]
    parts.append(f"export const {name} = {json.dumps(abi)} as const;\n")
header = "// Generated by contracts/script/export_abi.py from forge build output. Do not edit.\n"
(root.parent / "web/src/lib/abi.ts").write_text(header + "\n".join(parts))
